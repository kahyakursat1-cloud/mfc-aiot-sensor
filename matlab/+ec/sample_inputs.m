function X = sample_inputs(n)
%SAMPLE_INPUTS Physically motivated input distributions shared by Monte Carlo and Sobol.
%   Columns: P_MFC, t_active, eta_PMIC, P_leak, sensor-current multiplier, sleep floor.
tri = makedist('Triangular', 'a', 1.5, 'b', 2.0, 'c', 3.0);
X = [clip(lognrnd(log(150e-6), 0.20, n, 1), 80e-6, 400e-6), ...
     clip(random(tri, n, 1), 1.5, 3.0), ...
     (0.71 + 0.25*betarnd(5, 2, n, 1)).*(0.86 + 0.07*betarnd(4, 3, n, 1)), ...
     clip(lognrnd(log(5e-6), 0.5, n, 1), 1e-6, 25e-6), ...
     clip(normrnd(1.0, 0.15, n, 1), 0.6, 1.4), ...
     clip(normrnd(33e-6, 3e-6, n, 1), 25e-6, 40e-6)];
end

function y = clip(x, lo, hi)
y = min(max(x, lo), hi);
end
